#!/usr/bin/env node
/* Writes course/manifest.js: the lesson files the page loads, in name order. Run after adding or renaming a lesson. */
"use strict";
const fs = require("fs"), path = require("path");
const dir = path.join(__dirname, "..", "lessons");
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".js")).sort() : [];
fs.writeFileSync(path.join(__dirname, "..", "manifest.js"), "/* Generated by course/dev/manifest.js. The lesson files, in load order. */\nCourse.manifest = " + JSON.stringify(files, null, 1).replace(/\n\s*/g, " ") + ";\n");
console.log("manifest: " + files.length + " files");
